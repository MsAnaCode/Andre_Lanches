-- 1. Tabela de Produtos do Cardápio
CREATE TABLE IF NOT EXISTS public.produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  categoria TEXT NOT NULL CHECK (categoria IN ('Lanches', 'Porções', 'Bebidas')),
  preco NUMERIC(10, 2) NOT NULL,
  descricao TEXT NOT NULL,
  imagem_chave TEXT NOT NULL,
  destaque BOOLEAN NOT NULL DEFAULT FALSE,
  mais_vendido BOOLEAN NOT NULL DEFAULT FALSE,
  selo_promocao TEXT,
  disponivel BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabela de Mensagens da Tela "Contato"
CREATE TABLE IF NOT EXISTS public.mensagens_contato (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  contato TEXT NOT NULL,
  assunto TEXT NOT NULL DEFAULT 'Dúvida',
  mensagem TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabela de Pedidos Rápidos
CREATE TABLE IF NOT EXISTS public.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id BIGINT REFERENCES public.produtos(id) ON DELETE SET NULL,
  produto_nome TEXT NOT NULL,
  valor NUMERIC(10, 2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'recebido',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- Segurança (RLS) para testes acadêmicos via chave anon pública
-- ============================================================================
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mensagens_contato ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Leitura pública de produtos" ON public.produtos;
CREATE POLICY "Leitura pública de produtos"
  ON public.produtos FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Inserção pública de mensagens" ON public.mensagens_contato;
CREATE POLICY "Inserção pública de mensagens"
  ON public.mensagens_contato FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Inserção pública de pedidos" ON public.pedidos;
CREATE POLICY "Inserção pública de pedidos"
  ON public.pedidos FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

